-- Phantom Thieves Route | PostgreSQL schema
-- Jalankan setelah terhubung ke database phantom_thieves_route.
CREATE SCHEMA IF NOT EXISTS phantom_route;
SET search_path TO phantom_route, public;

CREATE TABLE IF NOT EXISTS game_dates (
    game_date_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_date DATE NOT NULL UNIQUE,
    weekday VARCHAR(10) NOT NULL CHECK (weekday IN ('Monday','Tuesday','Wednesday','Thursday','Friday','Saturday','Sunday')),
    notes TEXT
);

CREATE TABLE IF NOT EXISTS activities (
    activity_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_name VARCHAR(100) NOT NULL UNIQUE,
    category VARCHAR(50) NOT NULL,
    description TEXT
);

CREATE TABLE IF NOT EXISTS calendar_activities (
    calendar_activity_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_date_id BIGINT NOT NULL REFERENCES game_dates(game_date_id) ON DELETE CASCADE,
    activity_id BIGINT NOT NULL REFERENCES activities(activity_id) ON DELETE RESTRICT,
    session VARCHAR(20) NOT NULL CHECK (session IN ('Morning','After School','Evening')),
    condition_name VARCHAR(100) NOT NULL DEFAULT 'Normal',
    knowledge_gain INTEGER NOT NULL DEFAULT 0 CHECK (knowledge_gain >= 0),
    proficiency_gain INTEGER NOT NULL DEFAULT 0 CHECK (proficiency_gain >= 0),
    guts_gain INTEGER NOT NULL DEFAULT 0 CHECK (guts_gain >= 0),
    kindness_gain INTEGER NOT NULL DEFAULT 0 CHECK (kindness_gain >= 0),
    charm_gain INTEGER NOT NULL DEFAULT 0 CHECK (charm_gain >= 0),
    notes TEXT,
    UNIQUE (game_date_id, activity_id, session, condition_name)
);

CREATE TABLE IF NOT EXISTS player_profiles (
    player_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_name VARCHAR(100) NOT NULL,
    current_game_date_id BIGINT REFERENCES game_dates(game_date_id) ON DELETE SET NULL,
    knowledge SMALLINT NOT NULL DEFAULT 0 CHECK (knowledge BETWEEN 0 AND 5),
    proficiency SMALLINT NOT NULL DEFAULT 0 CHECK (proficiency BETWEEN 0 AND 5),
    guts SMALLINT NOT NULL DEFAULT 0 CHECK (guts BETWEEN 0 AND 5),
    kindness SMALLINT NOT NULL DEFAULT 0 CHECK (kindness BETWEEN 0 AND 5),
    charm SMALLINT NOT NULL DEFAULT 0 CHECK (charm BETWEEN 0 AND 5),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS confidants (
    confidant_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    confidant_name VARCHAR(100) NOT NULL UNIQUE,
    arcana VARCHAR(50),
    notes TEXT
);

CREATE TABLE IF NOT EXISTS player_confidant_ranks (
    player_id BIGINT NOT NULL REFERENCES player_profiles(player_id) ON DELETE CASCADE,
    confidant_id BIGINT NOT NULL REFERENCES confidants(confidant_id) ON DELETE CASCADE,
    current_rank SMALLINT NOT NULL DEFAULT 0 CHECK (current_rank BETWEEN 0 AND 10),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (player_id, confidant_id)
);

CREATE TABLE IF NOT EXISTS confidant_interactions (
    interaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    confidant_id BIGINT NOT NULL REFERENCES confidants(confidant_id) ON DELETE CASCADE,
    rank_target SMALLINT NOT NULL CHECK (rank_target BETWEEN 1 AND 10),
    interaction_description TEXT NOT NULL,
    answer_text TEXT NOT NULL,
    affection_points SMALLINT NOT NULL DEFAULT 0 CHECK (affection_points >= 0),
    is_spoiler BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS qa_entries (
    qa_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_date_id BIGINT REFERENCES game_dates(game_date_id) ON DELETE SET NULL,
    question_type VARCHAR(20) NOT NULL CHECK (question_type IN ('Class','Crossword')),
    question_text TEXT NOT NULL,
    answer_text TEXT NOT NULL,
    explanation TEXT,
    is_spoiler BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS personas (
    persona_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    persona_name VARCHAR(100) NOT NULL UNIQUE,
    level SMALLINT NOT NULL CHECK (level > 0),
    arcana VARCHAR(50),
    notes TEXT
);

CREATE TABLE IF NOT EXISTS fusion_recipes (
    recipe_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_persona_id BIGINT NOT NULL REFERENCES personas(persona_id) ON DELETE CASCADE,
    recipe_name VARCHAR(100),
    source_name VARCHAR(150),
    notes TEXT
);

CREATE TABLE IF NOT EXISTS fusion_recipe_materials (
    recipe_id BIGINT NOT NULL REFERENCES fusion_recipes(recipe_id) ON DELETE CASCADE,
    material_slot SMALLINT NOT NULL CHECK (material_slot > 0),
    persona_id BIGINT NOT NULL REFERENCES personas(persona_id) ON DELETE RESTRICT,
    PRIMARY KEY (recipe_id, material_slot)
);

CREATE TABLE IF NOT EXISTS bosses (
    boss_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    boss_name VARCHAR(150) NOT NULL UNIQUE,
    first_available_date_id BIGINT REFERENCES game_dates(game_date_id) ON DELETE SET NULL,
    last_available_date_id BIGINT REFERENCES game_dates(game_date_id) ON DELETE SET NULL,
    is_optional BOOLEAN NOT NULL DEFAULT FALSE,
    description TEXT,
    is_spoiler BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS boss_affinities (
    affinity_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    boss_id BIGINT NOT NULL REFERENCES bosses(boss_id) ON DELETE CASCADE,
    element VARCHAR(30) NOT NULL,
    affinity_type VARCHAR(20) NOT NULL CHECK (affinity_type IN ('Weak','Resist','Null','Repel','Drain','Block','Normal')),
    notes TEXT,
    UNIQUE (boss_id, element)
);

CREATE TABLE IF NOT EXISTS party_members (
    party_member_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS recommended_party_members (
    boss_id BIGINT NOT NULL REFERENCES bosses(boss_id) ON DELETE CASCADE,
    party_member_id BIGINT NOT NULL REFERENCES party_members(party_member_id) ON DELETE CASCADE,
    recommendation_notes TEXT,
    PRIMARY KEY (boss_id, party_member_id)
);

CREATE INDEX IF NOT EXISTS idx_calendar_activities_date_session ON calendar_activities(game_date_id, session);
CREATE INDEX IF NOT EXISTS idx_confidant_interactions_rank ON confidant_interactions(confidant_id, rank_target);
CREATE INDEX IF NOT EXISTS idx_bosses_dates ON bosses(first_available_date_id, last_available_date_id);
CREATE INDEX IF NOT EXISTS idx_boss_affinities_boss ON boss_affinities(boss_id);
